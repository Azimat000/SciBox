/**
 * В шапке только имя: полное «Имя Фамилия» рядом с меню, переключателем и тремя значками не помещается
 * и обрезается («Дмитрий Кор…»). Полное имя и почта открываются в самом меню.
 * Первое слово короче трёх букв («Д.») ничего не говорит, тогда показываем имя целиком.
 */
export function shortName(name: string): string {
  const first = name.trim().split(/\s+/)[0] ?? ''
  return first.replace(/\.$/, '').length >= 3 ? first : name
}
