/**
 * Ссылка `mailto:` для адреса из профиля или отклика. Знаки «?», «&», «=» в адресе иначе стали бы параметрами письма
 * (скрытая копия, готовый текст); сервер такие адреса не принимает, но старые записи и чужие данные не доверенные.
 */
export function mailtoHref(email: string): string {
  return `mailto:${encodeURIComponent(email).replaceAll('%40', '@')}`
}
