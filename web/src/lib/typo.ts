/** Короткие слова, которые в русском наборе не оставляют висеть в конце строки. */
const SHORT = /(^|[\s«(])([а-яёА-ЯЁ]{1,2}) /g
/** Тире не начинает строку: пробел перед ним неразрывный. */
const DASH = / ([—–])/g

/**
 * Русская типографика для текста из базы и заголовков: предлог, союз или частица из одной-двух букв склеиваются
 * со следующим словом неразрывным пробелом, тире со словом перед ним.
 */
export function typo(text: string): string {
  // Дважды: в «и в лаборатории» второе короткое слово стоит сразу за первым, и одно совпадение его съедает
  return text.replace(SHORT, '$1$2 ').replace(SHORT, '$1$2 ').replace(DASH, ' $1')
}
