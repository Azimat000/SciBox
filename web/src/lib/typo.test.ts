import { describe, expect, it } from 'vitest'
import { typo } from './typo'

const show = (s: string) => s.replace(/ /g, '_')

describe('typo', () => {
  it('склеивает короткое слово со следующим', () => {
    expect(show(typo('Найдите место в науке.'))).toBe('Найдите место в_науке.')
  })

  it('цепочка коротких слов и тире', () => {
    expect(show(typo('Работа и в лаборатории — и дома'))).toBe('Работа и_в_лаборатории_— и_дома')
  })

  it('кавычка и скобка перед коротким словом, латиница не трогается', () => {
    expect(show(typo('Тема «о плёнках» (в Томске) и ML at scale'))).toBe('Тема «о_плёнках» (в_Томске) и_ML at scale')
  })

  it('длинные слова и пустая строка без изменений', () => {
    expect(typo('Научный сотрудник')).toBe('Научный сотрудник')
    expect(typo('')).toBe('')
  })
})
