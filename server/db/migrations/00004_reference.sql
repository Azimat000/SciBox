-- Справочники (срез 5): специальности ВАК, регионы, должности и источники этих данных.
-- Источники и способ получения записаны в таблице reference_sources и в docs/REFERENCE.md.
-- Небольшие перечисления (уровни R1–R4, формат работы, финансирование, степени…) в базе не лежат: их значения проверяет сервер (internal/vacancies).

-- +goose Up
CREATE TABLE reference_sources (
    catalog    text PRIMARY KEY,
    title      text NOT NULL,
    url        text NOT NULL,
    edition    text NOT NULL,
    checked_on date NOT NULL
);

-- Номенклатура научных специальностей: область (1) → группа (1.1) → специальность (1.1.1).
CREATE TABLE science_fields (
    code text PRIMARY KEY CHECK (code ~ '^[1-9][0-9]*$'),
    name text NOT NULL
);
CREATE TABLE science_groups (
    code       text PRIMARY KEY CHECK (code ~ '^[1-9][0-9]*\.[0-9]+$'),
    field_code text NOT NULL REFERENCES science_fields (code),
    name       text NOT NULL
);
CREATE TABLE specialties (
    code       text PRIMARY KEY CHECK (code ~ '^[1-9][0-9]*\.[0-9]+\.[0-9]+$'),
    group_code text NOT NULL REFERENCES science_groups (code),
    name       text NOT NULL
);
CREATE INDEX specialties_group_idx ON specialties (group_code);

-- Субъекты РФ. Код: основной код региона на автомобильных номерах (двузначный); это служебный идентификатор.
CREATE TABLE regions (
    code text PRIMARY KEY CHECK (code ~ '^[0-9]{2}$'),
    name text NOT NULL UNIQUE
);

-- Должности. position_type: research — научные, teaching — ППС, early_career — аспирантура, постдок, стажировка, магистратура,
-- management — управление и инновационная инфраструктура (D-006). sort: порядок показа внутри типа.
CREATE TABLE positions (
    code          text     PRIMARY KEY CHECK (code ~ '^[a-z][a-z_]*$'),
    position_type text     NOT NULL CHECK (position_type IN ('research', 'teaching', 'early_career', 'management')),
    name          text     NOT NULL UNIQUE,
    sort          smallint NOT NULL
);

