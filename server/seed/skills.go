// withSkills возвращает основные поля учёного с его навыками из skillSets.
func withSkills(key string, core prof.CoreInput) prof.CoreInput {
	if sk, ok := skillSets[key]; ok {
		core.ResearchSkills = sk.research
		core.GeneralSkills = sk.general
	}
	return core
}
