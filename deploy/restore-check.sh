#!/bin/sh
# Проверка восстановления (срез 28, T-26): поднимает копию базы из хранилища копий рядом с рабочей и сверяет с ней.
# Рабочая база и хранилище копий не меняются. Запускать после настройки и затем раз в месяц (и после каждого
# изменения настроек копий): копия, которую ни разу не восстанавливали, копией не считается.
#
#   deploy/restore-check.sh                       боевой стенд
#   SCIBOX_DEPLOY_LOCAL=1 deploy/restore-check.sh репетиция на этом компьютере
set -eu
here=$(cd "$(dirname "$0")" && pwd)
dc="$here/compose"
echo "== снимок рабочей базы и отправка журнала в архив"
"$dc" exec -T backup scibox-archive-now
echo "== восстановление и сверка"
"$dc" --profile tools run --rm --no-deps -T restore-check
